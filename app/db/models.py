class Campervan(Base):
    __tablename__ = "campervans"

    id: Mapped[str] = mapped_column(String(50), primary_key=True)
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    type: Mapped[str | None] = mapped_column(String(50))
    capacity: Mapped[int] = mapped_column(Integer, nullable=False)
    price_per_day: Mapped[int] = mapped_column(Integer, nullable=False)
    base_city: Mapped[str] = mapped_column(String(100), nullable=False)
    features: Mapped[list[str] | None] = mapped_column(ARRAY(Text))
    description: Mapped[str | None] = mapped_column(Text)
    image_url: Mapped[str | None] = mapped_column(Text)
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    synced_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("now()"),
    )

    __table_args__ = (
        Index("idx_van_city", "base_city", "is_active"),
        Index("idx_van_capacity", "capacity", "price_per_day"),
    )


